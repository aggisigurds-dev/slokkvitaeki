-- ── 1. Taflan ────────────────────────────────────────────────────────────────────────────
create table if not exists public.krofu_verkferli (
  id               bigint generated by default as identity primary key,
  mal_lykill       text not null unique check (mal_lykill ~ '^(solur|fyrirtaeki|annad):'),
  tegund           text not null check (tegund in ('itreka','senda_krofu','payday_drog','krafa_ekki_stofnud','faera_kt',
                                                   'gleymt','greitt_sidar','aud_sala','stadfesta_greidslu','annad')),
  solur_id         bigint references public.solur(id) on delete set null,
  customer_base_id bigint references public.customers_base(id) on delete set null,
  fyrirtaeki_id    bigint references public.fyrirtaeki(id) on delete set null,
  upphaed          numeric,
  stada            text not null default 'opid'
                   check (stada in ('opid','tilbuid_i_vinnslu','i_vinnslu','i_yfirferd_agnars','lokid','sleppt')),
  skref            jsonb not null default '{}'::jsonb,
  gogn             jsonb not null default '{}'::jsonb,
  athugasemd       text,
  saga             jsonb not null default '[]'::jsonb,
  uppfaert_af      text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists krofu_verkferli_solur_idx on public.krofu_verkferli (solur_id);
create index if not exists krofu_verkferli_stada_idx on public.krofu_verkferli (stada);

