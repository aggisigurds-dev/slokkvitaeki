-- ── 2. Gikkur: updated_at + saga (viðbót, aldrei endurskrifuð) ───────────────────────────
create or replace function public.krofu_verkferli_stimpill()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := pg_catalog.now();
  if tg_op = 'INSERT' then
    new.saga := pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'kl', pg_catalog.now(), 'fra', null, 'til', new.stada, 'af', new.uppfaert_af));
  else
    new.created_at := old.created_at;
    new.saga := coalesce(old.saga, '[]'::jsonb);
    if new.stada is distinct from old.stada then
      new.saga := new.saga || pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
        'kl', pg_catalog.now(), 'fra', old.stada, 'til', new.stada, 'af', new.uppfaert_af));
    end if;
  end if;
  return new;
end
$$;

drop trigger if exists krofu_verkferli_stimpill on public.krofu_verkferli;
create trigger krofu_verkferli_stimpill
  before insert or update on public.krofu_verkferli
  for each row execute function public.krofu_verkferli_stimpill();

